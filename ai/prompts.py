def dialogue_focus(author, history):
    """Lightweight turn guidance; no extra model call or inferred user memory."""
    if author != 'austen':
        return ''
    latest=history[-1]['content']
    if re.search(r'질문.{0,12}(?:말아|말고|싫|그만)|(?:바로|지금|일단).{0,12}조언|어떻게.{0,12}(?:말|답장)|보낼.{0,6}(?:말|문장)', latest):
        return '이번 턴: 사용자가 질문 대신 조언이나 실제로 할 말을 요청했다. 추가 질문을 필수로 삼지 말고 확인된 사실 안에서 실용적인 답을 제시한다.'
    if len(history)==1:
        return '이번 턴: 먼저 고민의 상황을 알아본다. 성급한 원인 분석이나 해결책 대신, 사용자가 준 장면을 짚고 아직 모르는 핵심 하나만 질문한다. 구체적인 장면이 없으면 가장 최근의 말이나 행동을 묻는다. 이미 나온 사실은 다시 묻지 않는다.'
    return '이번 턴: 사용자의 방금 답한 내용으로 이전 생각을 갱신한다. 반복되는 행동과 서로의 기대 중 무엇이 확인됐는지 짚는다. 원인을 가를 정보가 부족하면 새 질문 하나, 충분하면 잠정적인 원인과 조언을 제시한다. 질문 수를 채우려 대화를 끌지 않는다.'

def reply_policy(author,history):
    from .scope import SAFETY
    latest=history[-1]['content']
    full=bool(SAFETY.search(latest) or re.search(r'자세|구체|조언|방법|해결|분석|설명|정리|예시|어떻게|현실적으로|보낼.{0,6}(말|문장)|질문.{0,12}(말고|말아|그만|싫)',latest))
    if full or (len(history)>3 and len(latest)>120):
        return {'mode':'advice','max_tokens':256 if author=='chekhov' else 400,'instruction':''}
    return {'mode':'brief','max_tokens':160 if author=='william' else 128,
            'instruction':'이번 턴은 1~2문장: 실제 상황을 짚고 필요한 질문 하나만 한다. 충분히 알면 질문 대신 짧게 조언한다. 위의 일반 답변 길이보다 우선한다.'}

